#!/usr/bin/env python3
"""Run Quoin's ignored checks that exercise real external verification tools."""

from __future__ import annotations

import os
import sys
from pathlib import Path

import wave2_evidence as evidence


def run() -> int:
    evidence.prepare()
    entries: list[dict] = []
    failed = False

    ea_value = os.environ.get("QUOIN_TEST_ENGINEERING_ASSURANCE") or os.environ.get("QUOIN_E2E_EA")
    ea_path = Path(ea_value).expanduser() if ea_value else None
    ea_available = bool(ea_path and ea_path.is_absolute() and ea_path.is_file() and os.access(ea_path, os.X_OK))
    ea_version = "unavailable"
    if ea_available:
        ea_version, _ = evidence.version([str(ea_path), "--version"])

    checks = [
        ("engineering-assurance-cli", "quoin-cli", "--lib", "analysis_evidence::tests", ["FR-153-AC-16", "FR-116-AC-18", "FR-153-AC-18"]),
        ("engineering-assurance-signed-chain", "quoin-cli", "--test", "tc_plat_1789_signed_approval_chain", ["FR-188-AC-1", "FR-188-AC-25"]),
    ]
    for name, package, test_kind, test_name, trace_ids in checks:
        config = {"tool": "engineering-assurance", "tool_version": ea_version,
                  "input": "throwaway signed/unsigned Git repositories generated by the ignored tests"}
        if not ea_available:
            config["execution_state"] = "not-executed"
            config["reason"] = "QUOIN_TEST_ENGINEERING_ASSURANCE or QUOIN_E2E_EA must name an executable"
            entries.append(evidence.entry(name, "error", config, trace_ids))
            failed = True
            continue
        env = os.environ.copy()
        env["QUOIN_TEST_ENGINEERING_ASSURANCE"] = str(ea_path)
        env["QUOIN_E2E_EA"] = str(ea_path)
        command = ["cargo", "test", "--locked", "--package", package]
        if test_kind == "--lib":
            command.extend(["--lib", test_name, "--", "--ignored"])
        else:
            command.extend([test_kind, test_name, "--", "--ignored"])
        log, status, error = evidence.execute(name, command, env)
        config.update({"execution_state": "executed", "input": config["input"], "log": log})
        if error:
            config["execution_state"] = "not-executed"
            config["reason"] = error
            entries.append(evidence.entry(name, "error", config, trace_ids))
            failed = True
        else:
            entries.append(evidence.entry(name, "pass" if status == 0 else "fail", config, trace_ids))
            failed |= status != 0

    report_value = os.environ.get("QUOIN_TEST_OSV_REPORT")
    mirror_date = os.environ.get("QUOIN_OSV_MIRROR_DATE")
    scanner_version, scanner_output = evidence.version(["osv-scanner", "--version"])
    report_path = Path(report_value).expanduser() if report_value else None
    osv_reasons = []
    if scanner_output is None:
        osv_reasons.append("osv-scanner is unavailable")
    if not report_path or not report_path.is_absolute() or not report_path.is_file():
        osv_reasons.append("QUOIN_TEST_OSV_REPORT must name an existing absolute authentic report")
    if not mirror_date:
        osv_reasons.append("QUOIN_OSV_MIRROR_DATE must supply the exact caller-used mirror date")
    osv_config = {"tool": "osv-scanner", "tool_version": scanner_version,
                  "input": str(report_path) if report_path else "missing"}
    if mirror_date:
        osv_config["osv_mirror_date"] = mirror_date
    if osv_reasons:
        osv_config.update({"execution_state": "not-executed", "reason": "; ".join(osv_reasons)})
        entries.append(evidence.entry("osv-authentic-report", "error", osv_config, ["FR-142-AC-19", "FR-149-AC-10"]))
        failed = True
    else:
        env = os.environ.copy()
        env["QUOIN_TEST_OSV_REPORT"] = str(report_path)
        log, status, error = evidence.execute(
            "osv-authentic-report",
            ["cargo", "test", "--locked", "--package", "quoin-soup", "--lib",
             "soup::advisory::osv_tests::tc_osv_scanner_authentic_ecosystem_report_is_parsed_and_joined",
             "--", "--ignored", "--exact"], env)
        osv_config.update({"execution_state": "executed", "log": log})
        if error:
            osv_config.update({"execution_state": "not-executed", "reason": error})
            entries.append(evidence.entry("osv-authentic-report", "error", osv_config, ["FR-142-AC-19", "FR-149-AC-10"]))
            failed = True
        else:
            entries.append(evidence.entry("osv-authentic-report", "pass" if status == 0 else "fail", osv_config,
                                          ["FR-142-AC-19", "FR-149-AC-10"]))
            failed |= status != 0

    results = evidence.ARTIFACTS / "real-tool-results.json"
    evidence.write_entries(results, entries)
    record_status = evidence.record("SUITE-004", "quoin-real-tool-test 1", results, "real-tool")
    if record_status:
        print(f"SUITE-004 evidence recording failed; see {evidence.ARTIFACTS / 'real-tool-record.log'}", file=sys.stderr)
        failed = True
    print(f"SUITE-004 raw logs and input: {evidence.ARTIFACTS}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(run())
