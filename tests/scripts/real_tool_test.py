#!/usr/bin/env python3
"""Run Quoin's ignored checks that exercise real external verification tools."""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

import wave2_evidence as evidence


def ignored_test_trace_ids(source: Path, test_names: set[str] | None = None) -> list[str]:
    """Read trace ids from ignored Rust tests, the authoritative test mapping."""
    lines = source.read_text(encoding="utf-8").splitlines()
    attributes: list[str] = []
    trace_ids: set[str] = set()
    index = 0
    while index < len(lines):
        line = lines[index]
        stripped = line.strip()
        if stripped.startswith("#["):
            attribute = [line]
            depth = line.count("[") - line.count("]")
            while depth > 0 and index + 1 < len(lines):
                index += 1
                attribute.append(lines[index])
                depth += lines[index].count("[") - lines[index].count("]")
            attributes.append("\n".join(attribute))
        elif stripped.startswith(("//", "///")) or not stripped:
            pass
        else:
            function = re.match(r"(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+([A-Za-z_][A-Za-z0-9_]*)\b", stripped)
            if function:
                name = function.group(1)
                if (any(attr.strip() == "#[test]" for attr in attributes)
                        and any(attr.lstrip().startswith("#[ignore") for attr in attributes)
                        and (test_names is None or name in test_names)):
                    for attr in attributes:
                        for trace in re.finditer(r"#\[trace\((.*?)\)\]", attr, re.DOTALL):
                            trace_ids.update(re.findall(r'"([^"\\]+)"', trace.group(1)))
            attributes = []
        index += 1
    return sorted(trace_ids)


def not_executed_entry(name: str, config: dict[str, str], trace_ids: list[str], reason: str) -> dict:
    config.update({"execution_state": "not-executed", "reason": reason})
    return evidence.entry(name, "error", config, trace_ids)


def run() -> int:
    evidence.prepare()
    entries: list[dict] = []
    failed = False

    ea_value = os.environ.get("QUOIN_TEST_ENGINEERING_ASSURANCE") or os.environ.get("QUOIN_E2E_EA")
    ea_path = Path(ea_value).expanduser() if ea_value else None
    ea_available = bool(ea_path and ea_path.is_absolute() and ea_path.is_file() and os.access(ea_path, os.X_OK))
    ea_version = "unavailable"
    if ea_available:
        ea_version, _ = evidence.version([str(ea_path), "--version"])

    checks = [
        ("engineering-assurance-cli", "quoin-cli", "--lib", None,
         "analysis_evidence::tests", "rust/crates/quoin-cli/src/analysis_evidence.rs"),
        ("engineering-assurance-signed-chain", "quoin-cli", "--test",
         "tc_plat_1789_signed_approval_chain", "a_signed_approval_with_the_permitted_meaning_is_approved_end_to_end",
         "rust/crates/quoin-cli/tests/tc_plat_1789_signed_approval_chain.rs"),
    ]
    for name, package, test_kind, target, test_name, source in checks:
        source_path = evidence.ROOT / source
        trace_ids = ignored_test_trace_ids(source_path, None if target is None else {test_name})
        config = {"tool": "engineering-assurance", "tool_version": ea_version,
                  "input": "throwaway signed/unsigned Git repositories generated by the ignored tests",
                  "trace_source": source, "trace_test_filter": test_name}
        if not trace_ids:
            entries.append(not_executed_entry(name, config, [],
                "no trace ids found on the ignored Rust tests selected by this lane"))
            failed = True
            continue
        if not ea_available:
            entries.append(not_executed_entry(name, config, trace_ids,
                "QUOIN_TEST_ENGINEERING_ASSURANCE or QUOIN_E2E_EA must name an executable"))
            failed = True
            continue
        env = os.environ.copy()
        env["QUOIN_TEST_ENGINEERING_ASSURANCE"] = str(ea_path)
        env["QUOIN_E2E_EA"] = str(ea_path)
        command = ["cargo", "test", "--locked", "--package", package]
        if test_kind == "--lib":
            command.extend(["--lib", test_name, "--", "--ignored"])
        else:
            command.extend([test_kind, target, test_name, "--", "--ignored", "--exact"])
        log, status, error = evidence.execute(name, command, env)
        config.update({"execution_state": "executed", "input": config["input"], "log": log})
        outcome, execution_state = evidence.classify_execution(status, error)
        config["execution_state"] = execution_state
        if error:
            config["reason"] = error
        entries.append(evidence.entry(name, outcome, config, trace_ids))
        failed |= outcome != "pass"

    report_value = os.environ.get("QUOIN_TEST_OSV_REPORT")
    mirror_date = os.environ.get("QUOIN_OSV_MIRROR_DATE")
    scanner_version, scanner_output = evidence.version(["osv-scanner", "--version"])
    report_path = Path(report_value).expanduser() if report_value else None
    osv_trace_ids = ignored_test_trace_ids(
        evidence.ROOT / "rust/crates/quoin-soup/src/soup/advisory/osv_tests.rs",
        {"tc_osv_scanner_authentic_ecosystem_report_is_parsed_and_joined"},
    )
    osv_reasons = []
    if not osv_trace_ids:
        osv_reasons.append("no trace ids found on the selected ignored Rust test")
    if scanner_output is None:
        osv_reasons.append("osv-scanner is unavailable")
    if not report_path or not report_path.is_absolute() or not report_path.is_file():
        osv_reasons.append("QUOIN_TEST_OSV_REPORT must name an existing absolute authentic report")
    if not mirror_date:
        osv_reasons.append("QUOIN_OSV_MIRROR_DATE must supply the exact caller-used mirror date")
    osv_config = {"tool": "osv-scanner", "tool_version": scanner_version,
                  "input": str(report_path) if report_path else "missing"}
    if mirror_date:
        osv_config["osv_mirror_date"] = mirror_date
    if osv_reasons:
        osv_config.update({"execution_state": "not-executed", "reason": "; ".join(osv_reasons)})
        entries.append(evidence.entry("osv-authentic-report", "error", osv_config, osv_trace_ids))
        failed = True
    else:
        env = os.environ.copy()
        env["QUOIN_TEST_OSV_REPORT"] = str(report_path)
        log, status, error = evidence.execute(
            "osv-authentic-report",
            ["cargo", "test", "--locked", "--package", "quoin-soup", "--lib",
             "soup::advisory::osv_tests::tc_osv_scanner_authentic_ecosystem_report_is_parsed_and_joined",
             "--", "--ignored", "--exact"], env)
        osv_config.update({"execution_state": "executed", "log": log})
        outcome, execution_state = evidence.classify_execution(status, error)
        osv_config["execution_state"] = execution_state
        if error:
            osv_config["reason"] = error
        entries.append(evidence.entry("osv-authentic-report", outcome, osv_config, osv_trace_ids))
        failed |= outcome != "pass"

    results = evidence.ARTIFACTS / "real-tool-results.json"
    evidence.write_entries(results, entries)
    record_status = evidence.record("SUITE-004", "quoin-real-tool-test 1", results, "real-tool")
    if record_status:
        print(f"SUITE-004 evidence recording failed; see {evidence.ARTIFACTS / 'real-tool-record.log'}", file=sys.stderr)
        failed = True
    print(f"SUITE-004 raw logs and input: {evidence.ARTIFACTS}")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(run())
