//! `generate` and `check` (FR-191).
//!
//! Every selected document is computed in memory before anything is written
//! or compared, so a run that exits 2 or 3 has touched nothing.

use std::fs;
use std::path::{Path, PathBuf};

use time::OffsetDateTime;
use time::format_description::well_known::Rfc3339;

use crate::error::{DossierError, DossierErrorCode};
use crate::gap::{Gap, sort_gaps};
use crate::registry::{DocumentSpec, Inputs, Registry};
use crate::report::{Comparison, DocumentReport, Report, Status};
use crate::writer::compose;

/// One document, computed in memory.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Rendered {
    /// Which document it is.
    pub spec: DocumentSpec,
    /// Where the file is, or would be written.
    pub path: PathBuf,
    /// The file's bytes.
    pub text: String,
    /// The gaps, in file order.
    pub gaps: Vec<Gap>,
}

impl Rendered {
    fn status(&self) -> Status {
        if self.gaps.is_empty() {
            Status::Complete
        } else {
            Status::Incomplete
        }
    }

    fn report(&self, comparison: Option<Comparison>) -> DocumentReport {
        DocumentReport {
            id: self.spec.id.to_owned(),
            kind: self.spec.kind.to_owned(),
            path: self.path.display().to_string(),
            status: self.status(),
            comparison,
            gaps: self.gaps.clone(),
        }
    }

    /// How the file on disk compares with these bytes. A missing or unreadable
    /// file counts as `differs` (FR-191, "Selection and check").
    #[must_use]
    pub fn compare(&self) -> Comparison {
        match fs::read(&self.path) {
            Ok(on_disk) if on_disk == self.text.as_bytes() => Comparison::Matches,
            _ => Comparison::Differs,
        }
    }
}

/// Validate the run-wide inputs and compute the selected documents.
///
/// # Errors
///
/// Exit 2 for a blank version, an invalid or missing `--as-of`, or an unknown
/// kind; exit 3 for the first generator whose source fails.
pub fn render(
    registry: &Registry,
    kinds: &[String],
    out: &Path,
    inputs: &Inputs,
) -> Result<Vec<Rendered>, DossierError> {
    if inputs.version.trim().is_empty() {
        return Err(DossierError::new(
            DossierErrorCode::VersionRequired,
            "--version is required: the version is part of the generated bytes",
        ));
    }
    if let Some(instant) = inputs.as_of.as_deref()
        && OffsetDateTime::parse(instant, &Rfc3339).is_err()
    {
        return Err(DossierError::new(
            DossierErrorCode::AsOfInvalid,
            format!("--as-of {instant:?} is not an RFC 3339 instant"),
        ));
    }
    let selected = registry.select(kinds)?;
    if inputs.as_of.is_none()
        && let Some(needy) = selected
            .iter()
            .map(|generator| generator.spec())
            .find(|spec| spec.needs_as_of)
    {
        return Err(DossierError::new(
            DossierErrorCode::AsOfRequired,
            format!("--as-of is required for {} ({})", needy.id, needy.kind),
        )
        .with_context("document", needy.id));
    }
    let mut rendered = Vec::with_capacity(selected.len());
    for generator in selected {
        let spec = generator.spec();
        let mut generated = generator
            .generate(inputs)
            .map_err(DossierError::source_failed)?;
        sort_gaps(&mut generated.gaps);
        let text = compose(
            &spec,
            &inputs.version,
            inputs.as_of.as_deref(),
            &generated.body,
            &generated.gaps,
        );
        rendered.push(Rendered {
            spec,
            path: out.join(format!("{}.md", spec.id)),
            text,
            gaps: generated.gaps,
        });
    }
    Ok(rendered)
}

/// Write the selected documents under `out`, touching nothing else there.
///
/// # Errors
///
/// As [`render`]; and exit 2 when `out` cannot be created, checked before any
/// file is written.
pub fn generate(
    registry: &Registry,
    kinds: &[String],
    out: &Path,
    inputs: &Inputs,
) -> Result<Report, DossierError> {
    let rendered = render(registry, kinds, out, inputs)?;
    ensure_out_dir(out)?;
    for document in &rendered {
        fs::write(&document.path, &document.text).map_err(|error| {
            DossierError::new(
                DossierErrorCode::WriteFailed,
                format!("cannot write {}: {error}", document.path.display()),
            )
            .with_context("path", document.path.display().to_string())
        })?;
    }
    Ok(Report {
        documents: rendered
            .iter()
            .map(|document| document.report(None))
            .collect(),
        ..Report::default()
    })
}

/// Compare the selected documents with the files on disk; writes nothing.
///
/// # Errors
///
/// As [`render`].
pub fn check(
    registry: &Registry,
    kinds: &[String],
    out: &Path,
    inputs: &Inputs,
) -> Result<Report, DossierError> {
    let rendered = render(registry, kinds, out, inputs)?;
    Ok(report_with_comparison(&rendered))
}

/// A report whose entries carry the comparison against disk.
#[must_use]
pub fn report_with_comparison(rendered: &[Rendered]) -> Report {
    Report {
        documents: rendered
            .iter()
            .map(|document| document.report(Some(document.compare())))
            .collect(),
        ..Report::default()
    }
}

/// Fail before writing if `out` cannot be created: the nearest existing
/// ancestor must be a writable directory. Then create it.
fn ensure_out_dir(out: &Path) -> Result<(), DossierError> {
    let unwritable = |reason: String| {
        DossierError::new(
            DossierErrorCode::OutUnwritable,
            format!("cannot create {}: {reason}", out.display()),
        )
        .with_context("path", out.display().to_string())
    };
    let existing = out
        .ancestors()
        .find(|ancestor| !ancestor.as_os_str().is_empty() && ancestor.exists())
        .unwrap_or_else(|| Path::new("."));
    let metadata = fs::metadata(existing).map_err(|error| unwritable(error.to_string()))?;
    if !metadata.is_dir() {
        return Err(unwritable(format!(
            "{} is not a directory",
            existing.display()
        )));
    }
    if metadata.permissions().readonly() {
        return Err(unwritable(format!("{} is read-only", existing.display())));
    }
    fs::create_dir_all(out).map_err(|error| unwritable(error.to_string()))
}

#[cfg(test)]
#[allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::indexing_slicing,
    clippy::panic,
    reason = "in a test, a panic IS the failure report; the production lints stand"
)]
mod tests {
    use super::*;
    use crate::error::SourceFailure;
    use crate::gap::GapKind;
    use crate::registry::{Generated, Generator};
    use ix_trace_rs::trace;

    struct Doc {
        spec: DocumentSpec,
        gaps: fn() -> Vec<Gap>,
        fail: bool,
    }

    impl Generator for Doc {
        fn spec(&self) -> DocumentSpec {
            self.spec
        }

        fn generate(&self, _: &Inputs) -> Result<Generated, SourceFailure> {
            if self.fail {
                return Err(SourceFailure {
                    source: "requirements".to_owned(),
                    detail: "unreadable".to_owned(),
                });
            }
            Ok(Generated {
                body: format!("# {}", self.spec.id),
                gaps: (self.gaps)(),
            })
        }
    }

    fn doc(kind: &'static str, id: &'static str, needs_as_of: bool) -> Doc {
        Doc {
            spec: DocumentSpec {
                kind,
                id,
                title: "T",
                needs_as_of,
            },
            gaps: Vec::new,
            fail: false,
        }
    }

    fn inputs() -> Inputs {
        Inputs {
            scope: PathBuf::from("."),
            modules: Vec::new(),
            clause_bindings: Vec::new(),
            pack: None,
            as_of: None,
            version: "1.0".to_owned(),
        }
    }

    fn registry(docs: Vec<Doc>) -> Registry {
        let mut registry = Registry::new();
        for doc in docs {
            registry.register(Box::new(doc)).unwrap();
        }
        registry
    }

    #[trace("FR-191-AC-1")]
    #[test]
    fn generate_writes_only_the_selected_files() {
        let work = tempfile::tempdir().unwrap();
        let out = work.path().join("dossier");
        fs::create_dir_all(&out).unwrap();
        fs::write(out.join("other.md"), "keep").unwrap();
        let registry = registry(vec![doc("a", "DOS-A", false), doc("b", "DOS-B", false)]);
        generate(&registry, &["b".to_owned()], &out, &inputs()).unwrap();
        let mut names: Vec<_> = fs::read_dir(&out)
            .unwrap()
            .map(|entry| entry.unwrap().file_name().into_string().unwrap())
            .collect();
        names.sort();
        assert_eq!(names, ["DOS-B.md", "other.md"]);
        assert_eq!(fs::read_to_string(out.join("other.md")).unwrap(), "keep");
    }

    #[trace("FR-191-AC-5")]
    #[test]
    fn check_reports_matches_then_differs_then_differs_for_a_missing_file_and_writes_nothing() {
        let work = tempfile::tempdir().unwrap();
        let out = work.path().join("dossier");
        let registry = registry(vec![doc("a", "DOS-A", false)]);
        let none: [String; 0] = [];
        let missing = check(&registry, &none, &out, &inputs()).unwrap();
        assert_eq!(missing.documents[0].comparison, Some(Comparison::Differs));
        assert!(!out.exists(), "check created a path");
        generate(&registry, &none, &out, &inputs()).unwrap();
        let current = check(&registry, &none, &out, &inputs()).unwrap();
        assert_eq!(current.documents[0].comparison, Some(Comparison::Matches));
        let file = out.join("DOS-A.md");
        let mut bytes = fs::read(&file).unwrap();
        bytes[0] = b'+';
        fs::write(&file, &bytes).unwrap();
        let edited = check(&registry, &none, &out, &inputs()).unwrap();
        assert_eq!(edited.documents[0].comparison, Some(Comparison::Differs));
        assert_eq!(fs::read(&file).unwrap(), bytes, "check rewrote the file");
    }

    #[trace("FR-191-AC-12")]
    #[test]
    fn a_failing_source_writes_nothing_and_leaves_existing_files_alone() {
        let work = tempfile::tempdir().unwrap();
        let out = work.path().join("dossier");
        fs::create_dir_all(&out).unwrap();
        fs::write(out.join("DOS-A.md"), "before").unwrap();
        let mut failing = doc("b", "DOS-B", false);
        failing.fail = true;
        let registry = registry(vec![doc("a", "DOS-A", false), failing]);
        let error = generate(&registry, &[], &out, &inputs()).unwrap_err();
        assert_eq!(error.code(), DossierErrorCode::SourceFailed);
        assert_eq!(error.source_failure().unwrap().source, "requirements");
        assert_eq!(fs::read_to_string(out.join("DOS-A.md")).unwrap(), "before");
        assert!(!out.join("DOS-B.md").exists());
    }

    #[trace("FR-191-AC-13")]
    #[test]
    fn a_blank_version_is_refused_before_anything_is_computed() {
        let registry = registry(vec![doc("a", "DOS-A", false)]);
        let mut inputs = inputs();
        inputs.version = "  ".to_owned();
        let work = tempfile::tempdir().unwrap();
        let error = generate(&registry, &[], &work.path().join("d"), &inputs).unwrap_err();
        assert_eq!(error.code(), DossierErrorCode::VersionRequired);
        assert!(!work.path().join("d").exists());
    }

    #[trace("FR-191-AC-3")]
    #[test]
    fn as_of_is_required_only_for_a_document_that_needs_it_and_must_parse() {
        let registry = registry(vec![doc("a", "DOS-A", false), doc("t", "DOS-T", true)]);
        let work = tempfile::tempdir().unwrap();
        let out = work.path().join("d");
        let only_a = ["a".to_owned()];
        assert!(generate(&registry, &only_a, &out, &inputs()).is_ok());
        let error = generate(&registry, &[], &out, &inputs()).unwrap_err();
        assert_eq!(error.code(), DossierErrorCode::AsOfRequired);
        let mut bad = inputs();
        bad.as_of = Some("yesterday".to_owned());
        let error = generate(&registry, &only_a, &out, &bad).unwrap_err();
        assert_eq!(error.code(), DossierErrorCode::AsOfInvalid);
        let mut good = inputs();
        good.as_of = Some("2026-11-15T00:00:00Z".to_owned());
        assert!(generate(&registry, &[], &out, &good).is_ok());
    }

    #[trace("FR-191-AC-17")]
    #[test]
    fn an_out_dir_that_cannot_be_created_is_refused_and_writes_nothing() {
        let work = tempfile::tempdir().unwrap();
        let blocker = work.path().join("file");
        fs::write(&blocker, "x").unwrap();
        let registry = registry(vec![doc("a", "DOS-A", false)]);
        let error = generate(&registry, &[], &blocker.join("sub"), &inputs()).unwrap_err();
        assert_eq!(error.code(), DossierErrorCode::OutUnwritable);
        assert_eq!(fs::read_to_string(&blocker).unwrap(), "x");
    }

    #[trace("FR-191-AC-14", "FR-191-AC-5")]
    #[test]
    fn gaps_are_sorted_and_the_same_in_the_report_and_the_file_and_runs_are_identical() {
        let mut gapped = doc("g", "DOS-G", false);
        gapped.gaps = || {
            vec![
                Gap::new(GapKind::NoEvidence, "FR-100-AC-2", "none")
                    .for_requirement("FR-100")
                    .for_criterion("FR-100-AC-2"),
                Gap::new(GapKind::NoRequirements, "document", "none"),
            ]
        };
        let registry = registry(vec![gapped]);
        let work = tempfile::tempdir().unwrap();
        let out = work.path().join("d");
        let first = generate(&registry, &[], &out, &inputs()).unwrap();
        let bytes = fs::read(out.join("DOS-G.md")).unwrap();
        let second = generate(&registry, &[], &out, &inputs()).unwrap();
        assert_eq!(first, second);
        assert_eq!(fs::read(out.join("DOS-G.md")).unwrap(), bytes);
        let kinds: Vec<_> = first.documents[0].gaps.iter().map(|g| g.gap_kind).collect();
        assert_eq!(kinds, [GapKind::NoRequirements, GapKind::NoEvidence]);
        let text = String::from_utf8(bytes).unwrap();
        assert!(
            text.contains(
                "- `no_requirements` document: none\n- `no_evidence` FR-100-AC-2: none\n"
            )
        );
        assert_eq!(first.documents[0].status, Status::Incomplete);
    }
}
