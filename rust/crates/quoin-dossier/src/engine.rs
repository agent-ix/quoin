//! `generate` and `check` (FR-191).
//!
//! Every selected document is computed in memory before anything is written
//! or compared, so a run that exits 2 or 3 has touched nothing.

use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};

use tempfile::TempPath;

use time::OffsetDateTime;
use time::format_description::well_known::Rfc3339;

use crate::error::{DossierError, DossierErrorCode};
use crate::gap::{Gap, sort_gaps};
use crate::registry::{DocumentSpec, Inputs, Registry};
use crate::report::{Comparison, DocumentReport, Report, Status};
use crate::writer::compose;

/// One document, computed in memory.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct Rendered {
    /// Which document it is.
    pub(crate) spec: DocumentSpec,
    /// Where the file is, or would be written.
    pub(crate) path: PathBuf,
    /// The file's bytes.
    pub(crate) text: String,
    /// The gaps, in file order.
    pub(crate) gaps: Vec<Gap>,
}

impl Rendered {
    fn status(&self) -> Status {
        if self.gaps.is_empty() {
            Status::Complete
        } else {
            Status::Incomplete
        }
    }

    fn report(&self, comparison: Option<Comparison>) -> DocumentReport {
        DocumentReport {
            id: self.spec.id.to_owned(),
            kind: self.spec.kind.to_owned(),
            path: self.path.display().to_string(),
            status: self.status(),
            comparison,
            gaps: self.gaps.clone(),
        }
    }

    /// How the file on disk compares with these bytes. A missing or unreadable
    /// file counts as `differs` (FR-191, "Selection and check").
    #[must_use]
    pub(crate) fn compare(&self) -> Comparison {
        match fs::read(&self.path) {
            Ok(on_disk) if on_disk == self.text.as_bytes() => Comparison::Matches,
            _ => Comparison::Differs,
        }
    }
}

/// Validate the run-wide inputs and compute the selected documents.
///
/// # Errors
///
/// Exit 2 for a blank version, an invalid or missing `--as-of`, or an unknown
/// kind; exit 3 for the first generator whose source fails.
pub(crate) fn render(
    registry: &Registry,
    kinds: &[String],
    out: &Path,
    inputs: &Inputs,
) -> Result<Vec<Rendered>, DossierError> {
    if inputs.version.trim().is_empty() {
        return Err(DossierError::new(
            DossierErrorCode::VersionRequired,
            "--version is required: the version is part of the generated bytes",
        ));
    }
    if let Some(instant) = inputs.as_of.as_deref()
        && OffsetDateTime::parse(instant, &Rfc3339).is_err()
    {
        return Err(DossierError::new(
            DossierErrorCode::AsOfInvalid,
            format!("--as-of {instant:?} is not an RFC 3339 instant"),
        ));
    }
    let selected = registry.select(kinds)?;
    if inputs.as_of.is_none()
        && let Some(needy) = selected
            .iter()
            .map(|generator| generator.spec())
            .find(|spec| spec.needs_as_of)
    {
        return Err(DossierError::new(
            DossierErrorCode::AsOfRequired,
            format!("--as-of is required for {} ({})", needy.id, needy.kind),
        )
        .with_context("document", needy.id));
    }
    let mut rendered = Vec::with_capacity(selected.len());
    for generator in selected {
        let spec = generator.spec();
        let mut generated = generator
            .generate(inputs)
            .map_err(DossierError::source_failed)?;
        sort_gaps(&mut generated.gaps);
        let text = compose(
            &spec,
            &inputs.version,
            inputs.as_of.as_deref(),
            &generated.body,
            &generated.gaps,
        );
        rendered.push(Rendered {
            spec,
            path: out.join(format!("{}.md", spec.id)),
            text,
            gaps: generated.gaps,
        });
    }
    Ok(rendered)
}

/// Write the selected documents under `out`, touching nothing else there.
///
/// # Errors
///
/// As [`render`]; and exit 2 when `out` cannot be created, checked before any
/// file is written.
pub fn generate(
    registry: &Registry,
    kinds: &[String],
    out: &Path,
    inputs: &Inputs,
) -> Result<Report, DossierError> {
    let rendered = render(registry, kinds, out, inputs)?;
    ensure_out_dir(out)?;
    commit(&rendered)?;
    Ok(Report {
        documents: rendered
            .iter()
            .map(|document| document.report(None))
            .collect(),
        ..Report::default()
    })
}

/// A destination this run has replaced or is about to.
struct Step<'a> {
    dest: &'a Path,
    /// The original, moved aside to a path this run owns.
    backup: Option<TempPath>,
    /// Whether the new file is in place at `dest`.
    placed: bool,
}

/// Replace the files of `rendered` all or nothing, short of outside
/// interference with the directory.
///
/// FR-191 leaves existing files unmodified on exit 2 and touches nothing but
/// the files it was asked for. Every destination is checked first (a
/// directory, say, is refused before anything changes); every new file is then
/// staged in the output directory under a unique name this run created, so an
/// unrelated file with any name is never opened; and each original is moved
/// to a unique owned backup before its replacement is linked in without
/// overwriting. If a step fails, the files already replaced are removed and
/// their originals renamed back. A rename back that fails is reported, and the
/// backup is kept rather than deleted.
///
/// Another process writing into the directory during the run is not guarded
/// against: a file it creates at a destination makes the link fail and is
/// preserved, but there is no directory lock.
fn commit(rendered: &[Rendered]) -> Result<(), DossierError> {
    let failed = |path: &Path, reason: &str| {
        DossierError::new(
            DossierErrorCode::WriteFailed,
            format!("cannot write {}: {reason}", path.display()),
        )
        .with_context("path", path.display().to_string())
    };
    for document in rendered {
        match fs::symlink_metadata(&document.path) {
            Ok(metadata) if !metadata.is_file() => {
                return Err(failed(&document.path, "it is not a regular file"));
            }
            Err(error) if error.kind() != std::io::ErrorKind::NotFound => {
                return Err(failed(&document.path, &error.to_string()));
            }
            _ => {}
        }
    }
    // Dropping an unplaced staged file removes it.
    let mut staged = Vec::with_capacity(rendered.len());
    for document in rendered {
        let mut file = temp_beside(&document.path, document.spec.id, "tmp")
            .map_err(|error| failed(&document.path, &error.to_string()))?;
        file.write_all(document.text.as_bytes())
            .map_err(|error| failed(&document.path, &error.to_string()))?;
        staged.push(file);
    }
    let mut done: Vec<Step<'_>> = Vec::with_capacity(rendered.len());
    for (document, file) in rendered.iter().zip(staged) {
        let dest = document.path.as_path();
        let mut step = Step {
            dest,
            backup: None,
            placed: false,
        };
        let moved = if fs::symlink_metadata(dest).is_ok() {
            temp_beside(dest, document.spec.id, "bak")
                .map(tempfile::NamedTempFile::into_temp_path)
                .and_then(|backup| {
                    // Renaming over the reserved empty backup replaces it.
                    fs::rename(dest, &backup)?;
                    step.backup = Some(backup);
                    Ok(())
                })
        } else {
            Ok(())
        };
        let linked = moved.map_err(|error| error.to_string()).and_then(|()| {
            file.persist_noclobber(dest)
                .map(drop)
                .map_err(|error| error.error.to_string())
        });
        step.placed = linked.is_ok();
        done.push(step);
        if let Err(reason) = linked {
            let notes = roll_back(done);
            return Err(failed(
                &document.path,
                &std::iter::once(reason)
                    .chain(notes)
                    .collect::<Vec<_>>()
                    .join("; "),
            ));
        }
    }
    // The new files are in place; a backup that cannot be removed is litter,
    // not a failure.
    drop(done);
    Ok(())
}

/// Undo the placements, newest first, and say what could not be undone.
fn roll_back(done: Vec<Step<'_>>) -> Vec<String> {
    let mut notes = Vec::new();
    for step in done.into_iter().rev() {
        if step.placed
            && let Err(error) = fs::remove_file(step.dest)
        {
            notes.push(format!("could not remove {}: {error}", step.dest.display()));
        }
        if let Some(backup) = step.backup
            && let Err(error) = fs::rename(&backup, step.dest)
        {
            let kept = backup
                .keep()
                .unwrap_or_else(|failure| failure.path.to_path_buf());
            notes.push(format!(
                "could not restore {}: {error}; the original is at {}",
                step.dest.display(),
                kept.display()
            ));
        }
    }
    notes
}

/// A new, uniquely named file beside `dest`. `tempfile` opens it exclusively,
/// so it can never be a file that already existed.
fn temp_beside(dest: &Path, id: &str, suffix: &str) -> std::io::Result<tempfile::NamedTempFile> {
    let dir = dest
        .parent()
        .filter(|parent| !parent.as_os_str().is_empty())
        .unwrap_or_else(|| Path::new("."));
    tempfile::Builder::new()
        .prefix(&format!(".{id}."))
        .suffix(&format!(".{suffix}"))
        .tempfile_in(dir)
}

/// Compare the selected documents with the files on disk; writes nothing.
///
/// # Errors
///
/// As [`render`].
pub fn check(
    registry: &Registry,
    kinds: &[String],
    out: &Path,
    inputs: &Inputs,
) -> Result<Report, DossierError> {
    let rendered = render(registry, kinds, out, inputs)?;
    Ok(report_with_comparison(&rendered))
}

/// A report whose entries carry the comparison against disk.
#[must_use]
pub(crate) fn report_with_comparison(rendered: &[Rendered]) -> Report {
    Report {
        documents: rendered
            .iter()
            .map(|document| document.report(Some(document.compare())))
            .collect(),
        ..Report::default()
    }
}

/// Fail before writing if `out` cannot be created: the nearest existing
/// ancestor must be a writable directory. Then create it.
fn ensure_out_dir(out: &Path) -> Result<(), DossierError> {
    let unwritable = |reason: String| {
        DossierError::new(
            DossierErrorCode::OutUnwritable,
            format!("cannot create {}: {reason}", out.display()),
        )
        .with_context("path", out.display().to_string())
    };
    let existing = out
        .ancestors()
        .find(|ancestor| !ancestor.as_os_str().is_empty() && ancestor.exists())
        .unwrap_or_else(|| Path::new("."));
    let metadata = fs::metadata(existing).map_err(|error| unwritable(error.to_string()))?;
    if !metadata.is_dir() {
        return Err(unwritable(format!(
            "{} is not a directory",
            existing.display()
        )));
    }
    if metadata.permissions().readonly() {
        return Err(unwritable(format!("{} is read-only", existing.display())));
    }
    fs::create_dir_all(out).map_err(|error| unwritable(error.to_string()))
}

