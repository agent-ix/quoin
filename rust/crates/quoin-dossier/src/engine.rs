    #[trace("FR-191-AC-14", "NFR-040-AC-1")]
    #[test]
    fn gaps_are_sorted_and_the_same_in_the_report_and_the_file_and_runs_are_identical() {
        let mut gapped = doc("g", "DOS-G", false);
        gapped.gaps = || {
            vec![
                Gap::new(GapKind::NoEvidence, "FR-100-AC-2", "none")
                    .for_requirement("FR-100")
                    .for_criterion("FR-100-AC-2"),
                Gap::new(GapKind::NoRequirements, "document", "none"),
            ]
        };
        let registry = registry(vec![gapped]);
        let work = tempfile::tempdir().unwrap();
        let out = work.path().join("d");
        let first = generate(&registry, &[], &out, &inputs()).unwrap();
        let bytes = fs::read(out.join("DOS-G.md")).unwrap();
        let second = generate(&registry, &[], &out, &inputs()).unwrap();
        assert_eq!(first, second);
        assert_eq!(fs::read(out.join("DOS-G.md")).unwrap(), bytes);
        let kinds: Vec<_> = first.documents[0].gaps.iter().map(|g| g.gap_kind).collect();
        assert_eq!(kinds, [GapKind::NoRequirements, GapKind::NoEvidence]);
        let text = String::from_utf8(bytes).unwrap();
        assert!(
            text.contains(
                "- `no_requirements` document: none\n- `no_evidence` FR-100-AC-2: none\n"
            )
        );
        assert_eq!(first.documents[0].status, Status::Incomplete);
    }
